"""Pretty-prints IR as Python source.

Regra de formatação: se uma chamada tem qualquer argumento que é ele
mesmo uma chamada, ela quebra em múltiplas linhas com um argumento por
linha. Isso produz saída legível para pipelines profundas.
"""
from ir import *


class PythonGenerator:
    WIDTH = 88

    def generate(self, prog: IRProgram) -> str:
        lines = ["# Generated by Flow transpiler", ""]
        for stmt in prog.stmts:
            lines.append(self.gen_stmt(stmt))
            lines.append("")  # linha em branco entre statements
        # remove o excesso final e adiciona um \n
        while lines and lines[-1] == "":
            lines.pop()
        return "\n".join(lines) + "\n"

    def gen_stmt(self, stmt) -> str:
        if isinstance(stmt, IRFnDef):
            params = ", ".join(stmt.params)
            body = self.gen_expr(stmt.body, 1)
            return f"def {stmt.name}({params}):\n    return {body}"
        if isinstance(stmt, IRAssign):
            return f"{stmt.name} = {self.gen_expr(stmt.value, 0)}"
        if isinstance(stmt, IRExprStmt):
            return self.gen_expr(stmt.expr, 0)
        raise Exception(f"unknown IR stmt: {stmt}")

    def gen_expr(self, node: IRNode, indent: int) -> str:
        if isinstance(node, IRVar):
            return node.name
        if isinstance(node, IRNum):
            return repr(node.value)
        if isinstance(node, IRStr):
            return repr(node.value)
        if isinstance(node, IRBool):
            return repr(node.value)

        if isinstance(node, IRBinOp):
            left = self.gen_expr(node.left, indent)
            right = self.gen_expr(node.right, indent)
            return f"{left} {node.op} {right}"

        if isinstance(node, IRUnOp):
            operand = self.gen_expr(node.operand, indent)
            if node.op == "not":
                return f"not {operand}"
            return f"{node.op}{operand}"

        if isinstance(node, IRList):
            inner = "    " * (indent + 1)
            outer = "    " * indent
            items = [self.gen_expr(i, indent + 1) for i in node.items]
            single = "[" + ", ".join(items) + "]"
            if "\n" not in single and len(single) <= self.WIDTH:
                return single
            body = ",\n".join(f"{inner}{self._indent_first(i, inner)}"
                              for i in items)
            return f"[\n{body}\n{outer}]"

        if isinstance(node, IRDict):
            inner = "    " * (indent + 1)
            outer = "    " * indent
            pairs = [(k, self.gen_expr(v, indent + 1)) for k, v in node.pairs]
            single = "{" + ", ".join(f"'{k}': {v}" for k, v in pairs) + "}"
            if "\n" not in single and len(single) <= self.WIDTH:
                return single
            body = ",\n".join(
                f"{inner}'{k}': {self._indent_first(v, inner)}"
                for k, v in pairs
            )
            return f"{{\n{body}\n{outer}}}"

        if isinstance(node, IRField):
            obj = self.gen_expr(node.obj, indent)
            # Registros Flow são dicts em Python → acesso por chave.
            # Objetos com atributos ficam de fora por enquanto; quando
            # isso mudar, o IR precisa ganhar um nó distinto.
            if isinstance(node.obj, (IRVar, IRField)):
                return f"{obj}['{node.field}']"
            return f"({obj})['{node.field}']"

        if isinstance(node, IRLambda):
            body = self.gen_expr(node.body, indent)
            return f"lambda {node.param}: {body}"

        if isinstance(node, IRCall):
            return self.gen_call(node, indent)

        raise Exception(f"unknown IR node: {node}")

    def gen_call(self, node: IRCall, indent: int) -> str:
        args = [self.gen_expr(a, indent + 1) for a in node.args]
        single = f"{node.func}({', '.join(args)})"
        if "\n" not in single and len(single) <= self.WIDTH:
            return single
        nested = any(isinstance(a, IRCall) for a in node.args)
        if not nested and len(single) <= self.WIDTH:
            return single
        inner = "    " * (indent + 1)
        outer = "    " * indent
        body = ",\n".join(f"{inner}{self._indent_first(a, inner)}" for a in args)
        return f"{node.func}(\n{body}\n{outer})"

    @staticmethod
    def _indent_first(s: str, indent: str) -> str:
        if "\n" not in s:
            return s
        lines = s.split("\n")
        return lines[0] + "\n" + "\n".join(lines[1:])